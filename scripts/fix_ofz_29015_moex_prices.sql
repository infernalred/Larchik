-- The paper is quoted on MOEX in percent of face value. For bonds the loader
-- stores full dirty price in the instrument currency: clean percent * face / 100 + accrued interest.

BEGIN;

WITH target AS (
    SELECT id
    FROM instruments
    WHERE upper(coalesce(ticker, '')) = 'RU000A1025A7'
       OR upper(coalesce(isin, '')) = 'RU000A1025A7'
    ORDER BY created_at
    LIMIT 1
), updated_instrument AS (
    UPDATE instruments i
    SET
        ticker = 'RU000A1025A7',
        isin = 'RU000A1025A7',
        name = 'ОФЗ 29015',
        type = 2,
        currency_id = 'RUB',
        exchange = 'MOEX',
        country = 'RU',
        is_trading = true,
        price_source = 'MOEX',
        updated_at = now()
    FROM target t
    WHERE i.id = t.id
    RETURNING i.id
), inserted_alias AS (
    INSERT INTO instrument_aliases (id, instrument_id, alias_code, normalized_alias_code)
    SELECT
        '55ce87b7-4587-4687-8588-e22db494f757'::uuid,
        t.id,
        'SU29015RMFS3',
        'SU29015RMFS3'
    FROM target t
    WHERE NOT EXISTS (
        SELECT 1
        FROM instrument_aliases ia
        WHERE ia.normalized_alias_code = 'SU29015RMFS3'
    )
    RETURNING instrument_id
), removed_tbank_prices AS (
    DELETE FROM prices p
    USING target t
    WHERE p.instrument_id = t.id
      AND upper(p.provider) = 'TBANK'
      AND p.date >= (DATE '2022-12-30'::timestamp AT TIME ZONE 'UTC')
    RETURNING p.id
)
SELECT
    (SELECT count(*) FROM updated_instrument) AS updated_instruments,
    (SELECT count(*) FROM inserted_alias) AS inserted_aliases,
    (SELECT count(*) FROM removed_tbank_prices) AS removed_tbank_prices;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM instruments
        WHERE upper(coalesce(isin, '')) = 'RU000A1025A7'
          AND upper(coalesce(price_source, '')) = 'MOEX'
          AND is_trading = true
    ) THEN
        RAISE EXCEPTION 'OFZ 29015 metadata validation failed: instrument is not configured for MOEX price sync.';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM instrument_aliases ia
        JOIN instruments i ON i.id = ia.instrument_id
        WHERE upper(coalesce(i.isin, '')) = 'RU000A1025A7'
          AND ia.normalized_alias_code = 'SU29015RMFS3'
    ) THEN
        RAISE EXCEPTION 'OFZ 29015 metadata validation failed: MOEX alias SU29015RMFS3 is missing.';
    END IF;
END $$;

COMMIT;



