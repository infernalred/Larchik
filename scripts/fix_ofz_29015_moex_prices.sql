BEGIN;

WITH target AS (
    SELECT id
    FROM instruments
    WHERE upper(coalesce(ticker, '')) = 'RU000A1025A7'
       OR upper(coalesce(isin, '')) = 'RU000A1025A7'
    ORDER BY created_at
    LIMIT 1
), removed_before_requested_start AS (
    DELETE FROM prices p
    USING target t
    WHERE p.instrument_id = t.id
      AND upper(p.provider) = 'MOEX'
      AND p.date < (DATE '2022-12-30'::timestamp AT TIME ZONE 'UTC')
    RETURNING p.id
), final_stats AS (
    SELECT
        count(*) AS moex_rows_from_start,
        min(p.date)::date AS first_moex_date,
        max(p.date)::date AS last_moex_date,
        min(p.value) AS min_value,
        max(p.value) AS max_value
    FROM prices p
    JOIN target t ON t.id = p.instrument_id
    WHERE upper(p.provider) = 'MOEX'
      AND p.date >= (DATE '2022-12-30'::timestamp AT TIME ZONE 'UTC')
)
SELECT
    (SELECT count(*) FROM removed_before_requested_start) AS removed_moex_rows_before_2022_12_30,
    moex_rows_from_start,
    first_moex_date,
    last_moex_date,
    min_value,
    max_value
FROM final_stats;

